"""Trace a flat Ask Zaen logo PNG into a clean multi-color SVG with VTracer.

The logo is traced one solid color layer at a time. This avoids the dark
overlap artifacts that can appear when VTracer receives a transparent,
multi-color raster as one stacked layer. No logo geometry is authored here;
every path comes from VTracer.
"""

from __future__ import annotations

import argparse
import html
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import vtracer
from PIL import Image


PALETTE = (
    (146, 160, 85, "#92A055"),
    (194, 118, 68, "#C27644"),
    (63, 77, 53, "#3F4D35"),
    (150, 86, 38, "#965626"),
)
SVG_NS = "http://www.w3.org/2000/svg"


def nearest_color(rgb: tuple[int, int, int]) -> int:
    return min(
        range(len(PALETTE)),
        key=lambda index: sum((rgb[channel] - PALETTE[index][channel]) ** 2 for channel in range(3)),
    )


def trace_layer(mask: Image.Image, color: str, temporary_directory: Path, debug_directory: Path | None = None) -> list[str]:
    layer_input = temporary_directory / f"layer-{color.removeprefix('#')}.png"
    layer_output = temporary_directory / f"layer-{color.removeprefix('#')}.svg"
    mask.save(layer_input)
    vtracer.convert_image_to_svg_py(
        str(layer_input),
        str(layer_output),
        colormode="binary",
        hierarchical="stacked",
        mode="spline",
        filter_speckle=8,
        color_precision=4,
        layer_difference=24,
        corner_threshold=70,
        length_threshold=8,
        max_iterations=6,
        splice_threshold=55,
        path_precision=2,
    )

    if debug_directory is not None:
        debug_directory.mkdir(parents=True, exist_ok=True)
        mask.save(debug_directory / f"layer-{color.removeprefix('#')}.png")
        (debug_directory / f"layer-{color.removeprefix('#')}.svg").write_text(
            layer_output.read_text(encoding="utf-8"), encoding="utf-8"
        )

    root = ET.parse(layer_output).getroot()
    paths: list[str] = []
    for path in root.iter(f"{{{SVG_NS}}}path"):
        fill = path.attrib.get("fill", "").lower()
        if fill in {"#ffffff", "white"}:
            continue
        attributes = [f'd="{html.escape(path.attrib["d"], quote=True)}"']
        if "transform" in path.attrib:
            attributes.append(f'transform="{html.escape(path.attrib["transform"], quote=True)}"')
        attributes.append(f'fill="{color}"')
        paths.append(f"  <path {' '.join(attributes)}/>")
    return paths


def trace_logo(source: Path, destination: Path, debug_directory: Path | None = None) -> None:
    image = Image.open(source).convert("RGBA")
    alpha = image.getchannel("A").point(lambda value: 255 if value >= 32 else 0)
    bounds = alpha.getbbox()
    if bounds is None:
        raise ValueError("logo image has no visible pixels")
    image = image.crop(bounds)
    alpha = alpha.crop(bounds)

    pixels = image.load()
    mask = alpha.load()
    labels = Image.new("L", image.size, 255)
    label_pixels = labels.load()
    for y in range(image.height):
        for x in range(image.width):
            if mask[x, y]:
                label_pixels[x, y] = nearest_color(pixels[x, y][:3])

    all_paths: list[str] = []
    with tempfile.TemporaryDirectory(prefix="askzaen-vtracer-") as temporary_directory:
        temp_dir = Path(temporary_directory)
        for index, (_, _, _, color) in enumerate(PALETTE):
            layer = Image.new("L", image.size, 255)
            layer_pixels = layer.load()
            for y in range(image.height):
                for x in range(image.width):
                    layer_pixels[x, y] = 0 if label_pixels[x, y] == index else 255
            all_paths.extend(trace_layer(layer, color, temp_dir, debug_directory))

    destination.parent.mkdir(parents=True, exist_ok=True)
    svg = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by VTracer 0.6.12; traced per color layer. -->',
        f'<svg version="1.1" xmlns="{SVG_NS}" width="{image.width}" height="{image.height}" viewBox="0 0 {image.width} {image.height}">',
        *all_paths,
        "</svg>",
    ]
    destination.write_text("\n".join(svg) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    parser.add_argument("--debug-dir", type=Path, default=None)
    arguments = parser.parse_args()
    trace_logo(arguments.source, arguments.destination, arguments.debug_dir)


if __name__ == "__main__":
    main()
