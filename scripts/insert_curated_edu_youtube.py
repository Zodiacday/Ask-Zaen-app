print(f"Total curated educational videos to insert: {len(edu_videos)}")

# Check if any are already present
inserted = 0
for v in edu_videos:
    c.execute("SELECT id FROM kids_media WHERE platform_url = ?", (v['platform_url'],))
    if c.fetchone():
        print(f"Already exists: {v['title']}")
        continue

    # Extract YouTube video id for high quality thumbnail
    import re
    match = re.search(r'(?:v=|\/)([0-9A-Za-z_-]{11})', v['platform_url'])
    yt_id = match.group(1) if match else ''
    poster_url = f"https://img.youtube.com/vi/{yt_id}/hqdefault.jpg"

    meta = {
        'image': poster_url,
        'youtube_id': yt_id,
        'curator_note': 'Curated Gold-Standard Educational YouTube Lesson for Calm Kids',
        'sensory_profile': {
            'visual_pace': 'low',
            'sound_intensity': 'low',
            'narrative_pressure': 'low',
            'emotional_arousal': 'low',
            'reward_pressure': 'low',
            'cuts_per_minute': v['cuts'],
            'recommended_routine': v['routine'],
            'parent_advisory': v['advisory']
        }
    }

    c.execute("""
        INSERT INTO kids_media (
            title, media_type, target_age_group, genre_category, duration, duration_seconds,
            platform_url, description, safety_rating_tags, creator_publisher, language,
            release_year, metadata_json, created_at, stimulation_score, stimulation_label
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, datetime('now'), ?, ?)
    """, (
        v['title'],
        v['media_type'],
        v['target_age_group'],
        v['genre_category'],
        v['duration'],
        v['duration_seconds'],
        v['platform_url'],
        v['description'],
        v['routine_tag'],
        v['creator_publisher'],
        'English',
        v['release_year'],
        json.dumps(meta, ensure_ascii=False),
        v['score'],
        'calm'
    ))
    inserted += 1

conn.commit()
print(f"Successfully inserted {inserted} new educational YouTube lessons!")

# Rebuild FTS
try:
    c.execute("INSERT INTO kids_media_fts(kids_media_fts) VALUES('rebuild')")
    conn.commit()
    print("FTS index rebuilt.")
except Exception as e:
    print("FTS note:", e)

conn.close()
