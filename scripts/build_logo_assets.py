import base64
import os
import re

svg_dir = 'assets/images/streaming'

def get_base64_svg(content):
    return 'data:image/svg+xml;base64,' + base64.b64encode(content.encode('utf-8')).decode('utf-8')

# Read and adjust for dark UI backgrounds
logos = {}

# 1. YouTube
with open(os.path.join(svg_dir, 'youtube.svg'), 'r', encoding='utf-8') as f:
    yt = f.read()
# Replace dark text fill: rgb(40, 40, 40) with #FFFFFF
yt = re.sub(r'fill:\s*rgb\(40,\s*40,\s*40\);?', 'fill: #FFFFFF;', yt)
yt = re.sub(r'style="fill:\s*#282828;?"', 'style="fill: #FFFFFF;"', yt)
logos['youtube'] = get_base64_svg(yt)

# 2. Disney+
with open(os.path.join(svg_dir, 'disney.svg'), 'r', encoding='utf-8') as f:
    disney = f.read()
# Replace dark blue fill #01147c with white #FFFFFF
disney = disney.replace('fill="#01147c"', 'fill="#FFFFFF"')
logos['disney'] = get_base64_svg(disney)

# 3. Netflix
with open(os.path.join(svg_dir, 'netflix.svg'), 'r', encoding='utf-8') as f:
    netflix = f.read()
# Netflix red is #E50914
netflix = netflix.replace('#d81f26', '#E50914')
logos['netflix'] = get_base64_svg(netflix)

# 4. Prime Video
with open(os.path.join(svg_dir, 'prime.svg'), 'r', encoding='utf-8') as f:
    prime = f.read()
# Ensure white/cyan contrast
logos['prime'] = get_base64_svg(prime)

# 5. Apple TV+
with open(os.path.join(svg_dir, 'apple.svg'), 'r', encoding='utf-8') as f:
    apple = f.read()
# Replace .a{fill:#333;} with .a{fill:#FFFFFF;}
apple = apple.replace('.a{fill:#333;}', '.a{fill:#FFFFFF;}')
apple = apple.replace('fill="#333"', 'fill="#FFFFFF"')
logos['apple'] = get_base64_svg(apple)

# 6. Paramount+
with open(os.path.join(svg_dir, 'paramount.svg'), 'r', encoding='utf-8') as f:
    paramount = f.read()
# In Paramount+, the mountain/text can be white with blue accent
paramount = paramount.replace('fill="#0064FF"', 'fill="#FFFFFF"')
logos['paramount'] = get_base64_svg(paramount)

# 7. PBS KIDS
with open(os.path.join(svg_dir, 'pbs.svg'), 'r', encoding='utf-8') as f:
    pbs = f.read()
logos['pbs'] = get_base64_svg(pbs)

# 8. CBeebies
with open(os.path.join(svg_dir, 'cbeebies.svg'), 'r', encoding='utf-8') as f:
    cbeebies = f.read()
logos['cbeebies'] = get_base64_svg(cbeebies)

# Write to constants/streamingLogosData.ts
out_ts = 'constants/streamingLogosData.ts'
with open(out_ts, 'w', encoding='utf-8') as f:
    f.write('// Autogenerated Official Vector SVG Data URIs for Streaming Platforms\n')
    f.write('export const STREAMING_LOGO_URIS: Record<string, string> = {\n')
    for k, v in logos.items():
        f.write(f'  "{k}": "{v}",\n')
    f.write('};\n')

print(f'Successfully built {out_ts} with {len(logos)} official SVGs!')
